fn parse_hex_rgba(hex: &str) -> u32 {
    let trimmed = hex.trim_start_matches('#');
    match trimmed.len() {
        6 => {
            let rgb = u32::from_str_radix(trimmed, 16)
                .unwrap_or_else(|_| panic!("Invalid 6-digit hex color: {hex}"));
            (rgb << 8) | 0xFF
        }
        8 => {
            let argb = u32::from_str_radix(trimmed, 16)
                .unwrap_or_else(|_| panic!("Invalid 8-digit hex color: {hex}"));
            let a = (argb >> 24) & 0xFF;
            let rgb = argb & 0x00FF_FFFF;
            (rgb << 8) | a
        }
        _ => panic!("Unsupported hex color length: {hex}"),
    }
}

